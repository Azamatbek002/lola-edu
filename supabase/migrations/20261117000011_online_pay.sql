-- Onlayn to'lov (Payme, Click)
--  • har bir o'quvchiga 6 xonali to'lov raqami (Payme/Click ilovasida kiritish va havola uchun)
--  • sozlamalar: Payme kassa ID, Click service/merchant ID (ochiq ma'lumot; maxfiy kalitlar — Supabase Secrets)
--  • ochiq to'lov sahifasi /pay/<raqam> uchun pay_info()
--  • eslatmalarga to'lov havolasi ({pay}) qo'shiladi — onlayn to'lov ulanganda
-- Hammasi qo'shimcha (additive): hech narsa o'chirilmaydi.
-- ════════════════════════════════════════════════════════════════════════════

-- 1) To'lov raqami ───────────────────────────────────────────────────────────
alter table students add column if not exists pay_code text;
comment on column students.pay_code is 'O''quvchining 6 xonali to''lov raqami (Payme/Click hisob raqami)';

create or replace function public.new_pay_code() returns text
language plpgsql volatile set search_path = public as $$
declare c text;
begin
  loop
    c := (100000 + floor(random() * 900000))::int::text;
    exit when not exists (select 1 from students where pay_code = c);
  end loop;
  return c;
end $$;
revoke all on function public.new_pay_code() from public, anon, authenticated;

create or replace function public.set_pay_code() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.pay_code is null or new.pay_code !~ '^\d{6}$' then
    new.pay_code := public.new_pay_code();
  end if;
  return new;
end $$;
revoke all on function public.set_pay_code() from public, anon, authenticated;

drop trigger if exists students_pay_code on students;
create trigger students_pay_code before insert on students for each row execute function public.set_pay_code();

-- Raqamni o'zgartirib bo'lmaydi (to'lov tizimlari unga bog'langan)
create or replace function public.protect_pay_code() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if old.pay_code is not null and new.pay_code is distinct from old.pay_code then
    new.pay_code := old.pay_code;
  end if;
  return new;
end $$;
revoke all on function public.protect_pay_code() from public, anon, authenticated;
drop trigger if exists students_protect_pay_code on students;
create trigger students_protect_pay_code before update on students for each row execute function public.protect_pay_code();

do $$
declare r record;
begin
  for r in select id from students where pay_code is null order by created_at loop
    update students set pay_code = public.new_pay_code() where id = r.id;
  end loop;
end $$;
alter table students alter column pay_code set not null;
create unique index if not exists students_pay_code_uq on students(pay_code);

-- 2) Tranzaksiyalar: Click uchun butun son ID va sinov belgisi ───────────────
alter table payment_transactions add column if not exists seq bigint generated by default as identity;
create unique index if not exists payment_transactions_seq_uq on payment_transactions(seq);
alter table payment_transactions add column if not exists is_test boolean not null default false;
comment on column payment_transactions.is_test is 'Payme sinov kaliti bilan kelgan (sandbox) — haqiqiy to''lov yaratilmaydi';

-- 3) Sozlamalar ──────────────────────────────────────────────────────────────
insert into settings (key, value)
values ('online_pay', jsonb_build_object('site_url', 'https://lola-edu.vercel.app'))
on conflict (key) do nothing;

-- 4) Ochiq to'lov sahifasi uchun: faqat yashirilgan ism va kassa ID'lari ─────
create or replace function public.pay_info(p_code text) returns jsonb
language sql stable security definer set search_path = public as $$
  select case when s.id is null then jsonb_build_object('ok', false)
  else jsonb_build_object(
    'ok', true,
    'code', s.pay_code,
    'name', split_part(trim(s.full_name), ' ', 1) ||
            coalesce(' ' || nullif(left(split_part(trim(s.full_name), ' ', 2), 1), '') || '.', ''),
    'center', coalesce((select value->>'name' from settings where key = 'center'), 'Lola Edu'),
    'payme', nullif(op.value->>'payme_merchant_id', ''),
    'click_service', nullif(op.value->>'click_service_id', ''),
    'click_merchant', nullif(op.value->>'click_merchant_id', '')
  ) end
  from (select 1) one
  left join students s on s.pay_code = p_code and s.status <> 'left'
  left join settings op on op.key = 'online_pay'
$$;
revoke all on function public.pay_info(text) from public;
grant execute on function public.pay_info(text) to anon, authenticated;

/** O'quvchi uchun to'lov havolasi matni (onlayn to'lov ulanmagan bo'lsa — bo'sh) */
create or replace function public.pay_link_text(p_code text, p_amount numeric) returns text
language sql stable security definer set search_path = public as $$
  select case
    when coalesce(op.value->>'payme_merchant_id', '') = '' and coalesce(op.value->>'click_service_id', '') = '' then ''
    else chr(10) || 'Onlayn to''lash (Payme, Click): ' || rtrim(coalesce(nullif(op.value->>'site_url', ''), 'https://lola-edu.vercel.app'), '/')
         || '/pay/' || p_code || case when p_amount > 0 then '?a=' || round(p_amount)::bigint else '' end
  end
  from settings op where op.key = 'online_pay'
$$;
revoke all on function public.pay_link_text(text, numeric) from public, anon, authenticated;

-- 5) Eslatmalar: {code} va {pay} o'zgaruvchilari ─────────────────────────────
create or replace function public.run_daily_jobs() returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  today date := (now() at time zone 'Asia/Tashkent')::date;
  cfg jsonb := coalesce((select value from settings where key = 'center'), '{}');
  charged int := 0; reminded int := 0; due_soon int := 0; bdays int := 0; trials int := 0;
  r record;
begin
  if extract(day from today) = 1 then
    charged := public.generate_monthly_charges(to_char(today, 'YYYY-MM'));
  end if;

  if coalesce((cfg->>'debt_alert')::boolean, true) then
    -- Muddati o'tgan: muddatdan keyingi kuni va keyin har 7 kunda
    for r in
      select s.*, x.debt, x.months from (
        select student_id, sum(remaining) as debt,
          string_agg(distinct to_char(to_date(month || '-01', 'YYYY-MM-DD'), 'MM.YYYY'), ', ') as months
        from charge_status where state = 'overdue'
        group by student_id
        having bool_or((today - due_date - 1) % 7 = 0)
      ) x join students s on s.id = x.student_id
      where s.status in ('active', 'frozen')
    loop
      perform public.queue_trigger('debt_reminder', coalesce(r.parent_phone, r.phone), coalesce(r.parent_telegram_chat_id, r.telegram_chat_id), r.full_name,
        jsonb_build_object('amount', to_char(r.debt, 'FM999G999G999') || ' so''m', 'month', r.months,
          'code', r.pay_code, 'pay', coalesce(public.pay_link_text(r.pay_code, r.debt), '')));
      reminded := reminded + 1;
    end loop;

    -- Ertaga to'lov kuni
    for r in
      select s.*, x.amt, x.due from (
        select student_id, sum(remaining) as amt, min(due_date) as due
        from charge_status where state = 'upcoming' and due_date = today + 1
        group by student_id
      ) x join students s on s.id = x.student_id
      where s.status = 'active'
    loop
      perform public.queue_trigger('payment_due', coalesce(r.parent_phone, r.phone), coalesce(r.parent_telegram_chat_id, r.telegram_chat_id), r.full_name,
        jsonb_build_object('amount', to_char(r.amt, 'FM999G999G999') || ' so''m', 'date', to_char(r.due, 'DD.MM.YYYY'),
          'code', r.pay_code, 'pay', coalesce(public.pay_link_text(r.pay_code, r.amt), '')));
      due_soon := due_soon + 1;
    end loop;
  end if;

  for r in select * from students where status = 'active' and birth_date is not null
           and extract(month from birth_date) = extract(month from today) and extract(day from birth_date) = extract(day from today) loop
    perform public.queue_trigger('birthday', r.phone, r.telegram_chat_id, r.full_name, '{}');
    bdays := bdays + 1;
  end loop;

  for r in select l.*, g.start_time from leads l left join groups g on g.id = l.trial_group_id
           where l.stage = 'trial_scheduled' and l.trial_date = today + 1 loop
    perform public.queue_trigger('trial_reminder', r.phone, null, r.full_name,
      jsonb_build_object('date', to_char(r.trial_date, 'DD.MM.YYYY'), 'time', coalesce(r.start_time, '')));
    trials := trials + 1;
  end loop;

  return jsonb_build_object('charged', charged, 'debt_reminders', reminded, 'due_reminders', due_soon, 'birthdays', bdays, 'trial_reminders', trials);
end $$;
revoke all on function public.run_daily_jobs() from public, anon, authenticated;

