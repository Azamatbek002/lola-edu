-- Eski standart matndagi "Payme/Click orqali to'lash mumkin." o'rniga endi aniq havola chiqadi.
update message_templates set text = rtrim(replace(text, ' Payme/Click orqali to''lash mumkin.', '')) || '{pay}'
where trigger in ('debt_reminder', 'payment_due') and position('{pay}' in text) = 0;
